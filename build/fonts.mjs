/* Download the faces this project sets and inline them as base64.
 *
 * Why: an SVG served through GitHub's camo proxy in an <img> runs in secure
 * static mode — external CSS never loads, so an @import of Google Fonts is a
 * no-op and the banner silently falls back to Georgia/Arial. Embedding turns
 * typography from "whatever the OS happens to have" into a fixed, measurable
 * choice: the pill and chip widths the header computes then match what
 * actually renders, on every machine and in both GitHub themes.
 *
 * Google subsets to the characters we actually set (the `text=` param), and
 * the subsets are kept per-asset for the same reason: a 76 KB font embedded in
 * six cards would be 450 KB of the README's image budget.
 *
 *   font-data.mjs        → banner: Newsreader 400 (the wordmark) + Inter
 *   font-data-cards.mjs  → cards:  Newsreader 500 (project names) only
 *
 * Newsreader = display, Inter = text: the locked Claude type system.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ALL_TEXT } from "./copy.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36";

async function take(spec, text) {
  const url = `${spec}&text=${encodeURIComponent([...new Set(text)].join(""))}&display=block`;
  const css = await (await fetch(url, { headers: { "User-Agent": UA } })).text();
  const faces = [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map((m) => m[1]);
  if (!faces.length) throw new Error(`no @font-face returned for ${spec}\n${css.slice(0, 400)}`);
  const out = [];
  for (const body of faces) {
    const family = /font-family:\s*'([^']+)'/.exec(body)[1];
    const weight = (/font-weight:\s*([\d\s]+);/.exec(body)?.[1] ?? "400").trim();
    const src = /url\((https:[^)]+)\)/.exec(body)[1];
    const font = await fetch(src, { headers: { "User-Agent": UA } });
    if (!font.ok) throw new Error(`font fetch ${font.status}`);
    const buf = Buffer.from(await font.arrayBuffer());
    out.push({ family, weight, bytes: buf.length, b64: buf.toString("base64") });
    console.log(`  ${family} ${weight}: ${(buf.length / 1024).toFixed(1)} KB`);
  }
  return out;
}

const toCss = (faces) =>
  faces
    .map(
      (f) =>
        `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${f.weight};` +
        `font-display:block;src:url(data:font/woff2;base64,${f.b64}) format('woff2')}`,
    )
    .join("");

const emit = (file, faces, label) => {
  const total = faces.reduce((n, f) => n + f.bytes, 0);
  writeFileSync(
    join(HERE, file),
    `/* generated by fonts.mjs — ${label}, ${(total / 1024).toFixed(1)} KB raw */\n` +
      `export const FONT_CSS = ${JSON.stringify(toCss(faces))};\n`,
  );
  console.log(`${file}: ${(total / 1024).toFixed(1)} KB raw → ${((total * 1.37) / 1024).toFixed(1)} KB base64`);
  return total;
};

console.log("subsetting banner…");
const banner = [
  ...(await take("https://fonts.googleapis.com/css2?family=Newsreader:opsz,wght@6..72,400", ALL_TEXT.bannerDisplay)),
  ...(await take("https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600", ALL_TEXT.bannerBody)),
];

console.log("subsetting cards…");
const cards = await take("https://fonts.googleapis.com/css2?family=Newsreader:opsz,wght@6..72,500", ALL_TEXT.cardDisplay);

emit("font-data.mjs", banner, "banner faces subset to the banner copy");
emit("font-data-cards.mjs", cards, "card display face subset to the project names");
